import assert from 'node:assert/strict'
import {pathToFileURL} from 'node:url'
const {chromium}=await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE || 'C:/Users/25490/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs').href)
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
  const page=await browser.newPage({viewport:{width:1280,height:650}})
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('http://127.0.0.1:5392/scripts/qa/compact-quote-fixture.html')
  await page.getByRole('button',{name:'复制图文表格',exact:true}).first().waitFor()
  await page.evaluate(()=>window.scrollTo(0,document.body.scrollHeight))
  const button=page.getByRole('button',{name:'回到顶部',exact:true}).first()
  await button.waitFor({state:'visible'})
  const initial=await button.boundingBox(),scroll=await page.evaluate(()=>window.scrollY)
  await page.mouse.move(initial.x+20,initial.y+20);await page.mouse.down()
  await page.mouse.move(initial.x-280,initial.y-180,{steps:12});await page.mouse.up()
  const moved=await button.boundingBox()
  assert.ok(Math.abs(moved.x-(initial.x-300))<2);assert.ok(Math.abs(moved.y-(initial.y-200))<2)
  assert.equal(await page.evaluate(()=>window.scrollY),scroll)
  await button.click();await page.waitForFunction(()=>window.scrollY<1)
  await page.evaluate(()=>window.scrollTo(0,document.body.scrollHeight));await button.waitFor({state:'visible'})
  const retained=await button.boundingBox();assert.ok(Math.abs(retained.x-moved.x)<2)
  await page.mouse.move(retained.x+20,retained.y+20);await page.mouse.down()
  await page.mouse.move(1278,648,{steps:10});await page.mouse.up()
  await page.setViewportSize({width:480,height:500})
  await page.waitForFunction(()=>{const b=document.querySelector('.quote-back-top')?.getBoundingClientRect();return b&&b.right<=window.innerWidth&&b.bottom<=window.innerHeight})
  assert.deepEqual(errors,[])
  await page.screenshot({path:'outputs/compact-quote/draggable-back-top.png'})
  console.log('PASS: native pointer drag, no accidental scroll, normal click, retained position and viewport resize.')
} finally {await browser.close()}
